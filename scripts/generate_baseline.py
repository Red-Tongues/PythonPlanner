"""Write the baseline migration from the master schema (``orchestrator.db.schema``).

    python scripts/generate_baseline.py

The migration holds the generated DDL as literal text and imports nothing from the application,
so it keeps working however the code changes. ``tests/test_schema.py`` fails whenever the master
schema and the baseline differ; run this script, review the diff and commit both.

While there is no live data, schema changes regenerate this one baseline (CFO decision Q4, build
tidy). Once a database must be kept, freeze the baseline and add new revisions instead.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

from orchestrator.db.models import Base
from orchestrator.db.schema import DIALECTS, schema_statements
from orchestrator.sql.views import ALL_VIEW_NAMES

TARGET = (
    Path(__file__).resolve().parents[1] / "src/orchestrator/db/migrations/versions/0001_baseline.py"
)

HEADER = '''"""Baseline schema: every table, trigger and view of the orchestrator database.

GENERATED by ``scripts/generate_baseline.py`` from the master schema
(``orchestrator.db.schema``: tables from ``db/models.py``, triggers from ``db/ddl.py``, views
from ``sql/views.py``). Do not edit by hand: change the master schema and regenerate.
``tests/test_schema.py`` fails if this file and the master schema differ.

The immutability and transition triggers here are the database guarantee behind Requirement F
(golden rule 1). They are never disabled, including in tests. Seed rows are not schema: they are
inserted by ``orchestrator.db.seed`` on every ``init-db``.

Revision ID: 0001_baseline
Revises: (none; replaces 0001-0007, squashed while there was no live data)
"""

from __future__ import annotations

from collections.abc import Sequence

from alembic import op

revision: str = "0001_baseline"
down_revision: str | None = None
branch_labels: str | Sequence[str] | None = None
depends_on: str | Sequence[str] | None = None


def _run(statements: Sequence[str]) -> None:
    # A raw DBAPI cursor called without parameters: neither SQLAlchemy nor psycopg then parse the
    # '%' (RAISE format) or ':' characters inside trigger bodies as placeholders.
    cursor = op.get_bind().connection.cursor()
    try:
        for statement in statements:
            cursor.execute(statement)
    finally:
        cursor.close()


def upgrade() -> None:
    _run(STATEMENTS[op.get_bind().dialect.name])


def downgrade() -> None:
    # Dropping the tables would erase the append-only audit log in one statement (DROP TABLE
    # bypasses row triggers), so a database with history is never downgraded to empty.
    events = op.get_bind().exec_driver_sql("SELECT COUNT(*) FROM events").scalar_one()
    if events:
        raise RuntimeError(f"{events} events exist: refusing to drop a database with history")
    dialect = op.get_bind().dialect.name
    drops = [f"DROP VIEW IF EXISTS {name}" for name in reversed(VIEWS)]
    if dialect == "postgresql":
        drops += [f"DROP TABLE IF EXISTS {name} CASCADE" for name in reversed(TABLES)]
        drops += [f"DROP FUNCTION IF EXISTS {name}() CASCADE" for name in FUNCTIONS]
    else:
        drops += [f"DROP TABLE IF EXISTS {name}" for name in reversed(TABLES)]
    _run(drops)


# --------------------------------------------------------------------------- generated
'''


def _literal(statement: str) -> str:
    if '"""' in statement or "\\" in statement:
        raise ValueError(f"cannot embed statement literally: {statement[:80]}")
    return f'"""{statement}"""'


def render() -> str:
    import re

    tables = [t.name for t in Base.metadata.sorted_tables]
    functions = sorted(
        {
            m.group(1)
            for s in schema_statements("postgresql")
            if (m := re.match(r"CREATE OR REPLACE FUNCTION (\w+)\(", s))
        }
    )
    out = [HEADER, "\nTABLES: tuple[str, ...] = (\n"]
    out += [f'    "{name}",\n' for name in tables]
    out.append(")\n\nVIEWS: tuple[str, ...] = (\n")
    out += [f'    "{name}",\n' for name in ALL_VIEW_NAMES]
    out.append(")\n\nFUNCTIONS: tuple[str, ...] = (\n")
    out += [f'    "{name}",\n' for name in functions]
    out.append(")\n\nSTATEMENTS: dict[str, list[str]] = {\n")
    for dialect in DIALECTS:
        out.append(f'    "{dialect}": [\n')
        out += [f"        {_literal(s)},\n" for s in schema_statements(dialect)]
        out.append("    ],\n")
    out.append("}\n")
    return "".join(out)


def main() -> None:
    TARGET.write_text(render())
    subprocess.run([sys.executable, "-m", "ruff", "format", "-q", str(TARGET)], check=True)
    print(f"wrote {TARGET}")


if __name__ == "__main__":
    main()
