"""Render the packet and run transition tables (``orchestrator.transitions``) as Markdown.

``docs/ARCHITECTURE.md`` §7 holds the output between the ``transition-tables`` markers;
``tests/test_transitions.py`` fails if they drift. Run ``python scripts/transition_tables.py``
to rewrite that block in place.
"""

from __future__ import annotations

from pathlib import Path

from orchestrator.transitions import PACKET_TRANSITIONS, RUN_TRANSITIONS, Rule

BEGIN = "<!-- transition-tables:begin (generated by scripts/transition_tables.py) -->"
END = "<!-- transition-tables:end -->"
DOC = Path(__file__).resolve().parents[1] / "docs" / "ARCHITECTURE.md"


def _actors(rule: Rule) -> str:
    names = {"system": "kernel", "user": "user"}
    return " / ".join(names[a.value] for a in sorted(rule.actors, key=lambda a: a.value))


def _cell(text: str) -> str:
    return text.replace("|", "\\|") or "—"


def _table(rules: dict[tuple[str, str], Rule]) -> str:
    lines = ["| From → To | Actor | Trigger | Guard | Dev. |", "|---|---|---|---|---|"]
    for (src, dst), rule in sorted(rules.items()):
        lines.append(
            f"| `{src}` → `{dst}` | {_actors(rule)} | {_cell(rule.trigger)} | "
            f"{_cell(rule.guard)} | {rule.deviation or ''} |"
        )
    return "\n".join(lines)


def render() -> str:
    return "\n".join(
        [
            BEGIN,
            "",
            "#### 7.1 Packet transitions",
            "",
            _table(PACKET_TRANSITIONS),
            "",
            "#### 7.2 Run transitions (`generation_runs.state`)",
            "",
            _table(RUN_TRANSITIONS),
            "",
            END,
        ]
    )


def main() -> None:
    text = DOC.read_text()
    if BEGIN in text:
        head, rest = text.split(BEGIN, 1)
        _, tail = rest.split(END, 1)
        text = head + render() + tail
    else:
        text = text.rstrip() + "\n\n" + render() + "\n"
    DOC.write_text(text)


if __name__ == "__main__":
    main()
