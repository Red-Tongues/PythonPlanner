"""M1.1 governance hardening (review R1 fixes 1, 2, 5, 6, 12; widening for fix 7).

* Fix 1 — superseded history is immutable: a project, objective or packet that has a successor
  rejects UPDATE and DELETE.
* Fix 2 — lineage invariants: a new lineage starts at version 1; a successor keeps the ref, has
  ``version = predecessor + 1`` and the predecessor's ancestry; ref, version, ``supersedes_id``
  and ancestry never change; a superseding version, or a row other rows depend on, cannot be
  deleted (archive instead). ``supersedes_id`` was already unique (one successor per row).
* Fix 5 — ``evaluation_passes``: ``eval_cycle_id`` NOT NULL and uniqueness over
  ``(packet_id, eval_cycle_id, field_name, pass_no, attempt)``.
* Fix 6 — ``ref_counters`` for atomic ref allocation, initialised from existing refs.
* Fix 12 — ``field_registry_revisions`` (append-only snapshots of the field registry).
* ``events.entity_id`` widened to 128 characters so setting keys fit (fix 7 matches events to
  rows by primary key).

FROZEN: all SQL is literal or generated by the helpers in this file only; nothing is imported
from the application. Never edit this file after it is applied; add a new revision instead.

SQLite note: column changes rebuild the table (batch mode), which drops its triggers, so the
append-only triggers of ``evaluation_passes`` and ``events`` are recreated here (and the 0002
versions are recreated on downgrade).

Revision ID: 0004
Revises: 0003
"""

from __future__ import annotations

import re
from collections.abc import Sequence

import sqlalchemy as sa
from alembic import op

revision: str = "0004"
down_revision: str | None = "0003"
branch_labels: str | Sequence[str] | None = None
depends_on: str | Sequence[str] | None = None

MARKER = "orchestrator-immutable"

#: table → (ancestry columns that a successor must share and that never change,
#:          SQL condition (on OLD) that means "other rows depend on this one")
LINEAGE: dict[str, tuple[tuple[str, ...], str]] = {
    "projects": (
        (),
        "EXISTS (SELECT 1 FROM objectives d WHERE d.project_id = OLD.id) "
        "OR EXISTS (SELECT 1 FROM packets d WHERE d.project_id = OLD.id)",
    ),
    "objectives": (
        ("project_id",),
        "EXISTS (SELECT 1 FROM packets d WHERE d.objective_id = OLD.id)",
    ),
    "packets": (
        ("project_id", "objective_id", "parent_id", "root_id"),
        "EXISTS (SELECT 1 FROM packets d WHERE d.id <> OLD.id "
        "AND (d.parent_id = OLD.id OR d.root_id = OLD.id)) "
        "OR EXISTS (SELECT 1 FROM evaluation_passes d WHERE d.packet_id = OLD.id) "
        "OR EXISTS (SELECT 1 FROM artifacts d WHERE d.packet_id = OLD.id) "
        "OR EXISTS (SELECT 1 FROM channel_runs d WHERE d.packet_id = OLD.id) "
        "OR EXISTS (SELECT 1 FROM quality_reports d WHERE d.packet_id = OLD.id)",
    ),
}
IMMUTABLE_LINEAGE_COLUMNS = ("ref", "version", "supersedes_id")
APPEND_ONLY = ("evaluation_passes", "events", "field_registry_revisions")


# --------------------------------------------------------------------------- SQLite


def _sqlite_trigger(name: str, timing: str, table: str, when: str, message: str) -> str:
    return (
        f"CREATE TRIGGER {name} {timing} ON {table} FOR EACH ROW WHEN {when} "
        f"BEGIN SELECT RAISE(ABORT, '{MARKER}: {message}'); END"
    )


def _sqlite_append_only(table: str) -> list[str]:
    # identical text to 0002's triggers, so the manifest fingerprints stay comparable
    return [
        _sqlite_trigger(
            f"trg_{table}_append_only_{op_}",
            f"BEFORE {op_.upper()}",
            table,
            "1 = 1",
            f"{table} is append-only ({op_} rejected)",
        )
        for op_ in ("update", "delete")
    ]


def _sqlite_lineage(table: str) -> list[str]:
    ancestry, dependents = LINEAGE[table]
    successor = f"EXISTS (SELECT 1 FROM {table} s WHERE s.supersedes_id = OLD.id)"
    same_ancestry = "".join(f" AND p.{c} IS NEW.{c}" for c in ancestry)
    valid_predecessor = (
        f"EXISTS (SELECT 1 FROM {table} p WHERE p.id = NEW.supersedes_id "
        f"AND p.ref = NEW.ref AND p.version + 1 = NEW.version{same_ancestry})"
    )
    changed = " OR ".join(
        f"NEW.{c} IS NOT OLD.{c}" for c in (*IMMUTABLE_LINEAGE_COLUMNS, *ancestry)
    )
    t = _sqlite_trigger
    return [
        t(
            f"trg_{table}_superseded_no_update",
            "BEFORE UPDATE",
            table,
            successor,
            f"superseded row in {table} is history and cannot be updated",
        ),
        t(
            f"trg_{table}_superseded_no_delete",
            "BEFORE DELETE",
            table,
            successor,
            f"superseded row in {table} is history and cannot be deleted",
        ),
        t(
            f"trg_{table}_successor_no_delete",
            "BEFORE DELETE",
            table,
            "OLD.supersedes_id IS NOT NULL",
            f"a superseding version in {table} cannot be deleted; archive instead",
        ),
        t(
            f"trg_{table}_dependents_no_delete",
            "BEFORE DELETE",
            table,
            dependents,
            f"row in {table} has dependents and cannot be deleted; archive instead",
        ),
        t(
            f"trg_{table}_lineage_no_rewrite",
            "BEFORE UPDATE",
            table,
            changed,
            f"lineage fields of {table} (ref, version, supersedes_id, ancestry) are immutable",
        ),
        t(
            f"trg_{table}_lineage_start",
            "BEFORE INSERT",
            table,
            "NEW.supersedes_id IS NULL AND NEW.version <> 1",
            f"a new lineage in {table} starts at version 1",
        ),
        t(
            f"trg_{table}_lineage_successor",
            "BEFORE INSERT",
            table,
            f"NEW.supersedes_id IS NOT NULL AND NOT {valid_predecessor}",
            f"a successor in {table} must keep the ref, have version = predecessor + 1 "
            "and the same ancestry",
        ),
    ]


def _sqlite_names(statements: list[str]) -> list[str]:
    return [re.match(r"CREATE TRIGGER (\w+)", s).group(1) for s in statements]  # type: ignore[union-attr]


# --------------------------------------------------------------------------- PostgreSQL


def _pg_raise(message: str, *args: str) -> str:
    fmt_args = "".join(f", {a}" for a in args)
    return f"RAISE EXCEPTION '{MARKER}: {message}'{fmt_args} USING ERRCODE = '23001';"


def _pg_lineage(table: str) -> list[str]:
    ancestry, dependents = LINEAGE[table]
    same_ancestry = "".join(f" AND p.{c} IS NOT DISTINCT FROM NEW.{c}" for c in ancestry)
    changed = " OR ".join(
        f"NEW.{c} IS DISTINCT FROM OLD.{c}" for c in (*IMMUTABLE_LINEAGE_COLUMNS, *ancestry)
    )
    fn = f"orch_{table}_lineage_guard"
    body = f"""CREATE OR REPLACE FUNCTION {fn}() RETURNS trigger LANGUAGE plpgsql AS $fn$
BEGIN
  IF TG_OP IN ('UPDATE', 'DELETE') THEN
    IF EXISTS (SELECT 1 FROM {table} s WHERE s.supersedes_id = OLD.id) THEN
      {_pg_raise("superseded row % in % is history (% rejected)", "OLD.ref", "TG_TABLE_NAME", "lower(TG_OP)")}
    END IF;
  END IF;
  IF TG_OP = 'DELETE' THEN
    IF OLD.supersedes_id IS NOT NULL THEN
      {_pg_raise("superseding version % v% in % cannot be deleted; archive instead", "OLD.ref", "OLD.version", "TG_TABLE_NAME")}
    END IF;
    IF {dependents} THEN
      {_pg_raise("row % in % has dependents and cannot be deleted; archive instead", "OLD.ref", "TG_TABLE_NAME")}
    END IF;
    RETURN OLD;
  END IF;
  IF TG_OP = 'UPDATE' THEN
    IF {changed} THEN
      {_pg_raise("lineage fields of % (ref, version, supersedes_id, ancestry) are immutable", "TG_TABLE_NAME")}
    END IF;
  END IF;
  IF TG_OP = 'INSERT' THEN
    IF NEW.supersedes_id IS NULL THEN
      IF NEW.version <> 1 THEN
        {_pg_raise("a new lineage in % starts at version 1", "TG_TABLE_NAME")}
      END IF;
    ELSIF NOT EXISTS (SELECT 1 FROM {table} p WHERE p.id = NEW.supersedes_id
                      AND p.ref = NEW.ref AND p.version + 1 = NEW.version{same_ancestry}) THEN
      {_pg_raise("a successor in % must keep the ref, have version = predecessor + 1 and the same ancestry", "TG_TABLE_NAME")}
    END IF;
  END IF;
  RETURN NEW;
END;
$fn$"""
    return [
        body,
        f"CREATE TRIGGER trg_{table}_lineage BEFORE INSERT OR UPDATE OR DELETE ON {table} "
        f"FOR EACH ROW EXECUTE FUNCTION {fn}()",
    ]


PG_REGISTRY_TRIGGERS = [
    "CREATE TRIGGER trg_field_registry_revisions_append_only BEFORE UPDATE OR DELETE ON "
    "field_registry_revisions FOR EACH ROW EXECUTE FUNCTION orch_append_only_guard()",
    "CREATE TRIGGER trg_field_registry_revisions_no_truncate BEFORE TRUNCATE ON "
    "field_registry_revisions FOR EACH STATEMENT EXECUTE FUNCTION orch_append_only_guard()",
]


# --------------------------------------------------------------------------- helpers


def _run(statements: Sequence[str]) -> None:
    cursor = op.get_bind().connection.cursor()
    try:
        for statement in statements:
            cursor.execute(statement)
    finally:
        cursor.close()


def _is_sqlite() -> bool:
    return op.get_bind().dialect.name == "sqlite"


def _init_ref_counters() -> None:
    bind = op.get_bind()
    counters: dict[str, int] = {}

    def bump(name: str, number: int) -> None:
        counters[name] = max(counters.get(name, 0), number)

    for (ref,) in bind.execute(sa.text("SELECT ref FROM projects")):
        bump("project", int(ref.removeprefix("P-")))
    for (ref,) in bind.execute(sa.text("SELECT ref FROM packets")):
        bump("packet", int(ref.removeprefix("PP-")))
    for (ref,) in bind.execute(sa.text("SELECT ref FROM objectives")):
        _, project_number, position = ref.split("-")
        bump(f"objective:{project_number}", int(position))
    if counters:
        table = sa.table(
            "ref_counters", sa.column("name", sa.String), sa.column("value", sa.Integer)
        )
        op.bulk_insert(table, [{"name": n, "value": v} for n, v in sorted(counters.items())])


# --------------------------------------------------------------------------- upgrade / downgrade


def upgrade() -> None:
    op.create_table(
        "ref_counters",
        sa.Column("name", sa.String(length=64), nullable=False),
        sa.Column("value", sa.Integer(), nullable=False),
        sa.PrimaryKeyConstraint("name", name=op.f("pk_ref_counters")),
    )
    _init_ref_counters()

    op.create_table(
        "field_registry_revisions",
        sa.Column("id", sa.String(length=36), nullable=False),
        sa.Column("revision", sa.Integer(), nullable=False),
        sa.Column("sha256", sa.String(length=64), nullable=False),
        sa.Column("field_count", sa.Integer(), nullable=False),
        sa.Column("definitions", sa.JSON(), nullable=False),
        sa.Column("created_at", sa.DateTime(timezone=True), nullable=False),
        sa.PrimaryKeyConstraint("id", name=op.f("pk_field_registry_revisions")),
        sa.UniqueConstraint("revision", name=op.f("uq_field_registry_revisions_revision")),
    )

    # Fix 5. Rows with a NULL cycle id cannot exist yet (nothing writes passes before M2); if
    # one does, the NOT NULL change fails loudly rather than rewriting append-only history.
    with op.batch_alter_table("evaluation_passes") as batch:
        batch.drop_constraint("uq_evaluation_passes_eval_cycle_id", type_="unique")
        batch.alter_column("eval_cycle_id", existing_type=sa.String(length=36), nullable=False)
        batch.create_unique_constraint(
            "uq_evaluation_passes_packet_id",
            ["packet_id", "eval_cycle_id", "field_name", "pass_no", "attempt"],
        )
    with op.batch_alter_table("events") as batch:
        batch.alter_column(
            "entity_id", existing_type=sa.String(length=36), type_=sa.String(length=128)
        )

    if _is_sqlite():
        statements = [s for t in APPEND_ONLY for s in _sqlite_append_only(t)]
        statements += [s for t in LINEAGE for s in _sqlite_lineage(t)]
    else:
        statements = [*PG_REGISTRY_TRIGGERS]
        statements += [s for t in LINEAGE for s in _pg_lineage(t)]
    _run(statements)


def downgrade() -> None:
    if _is_sqlite():
        names = _sqlite_names([s for t in LINEAGE for s in _sqlite_lineage(t)])
        names += _sqlite_names(_sqlite_append_only("field_registry_revisions"))
        _run([f"DROP TRIGGER IF EXISTS {n}" for n in names])
    else:
        drops = [f"DROP TRIGGER IF EXISTS trg_{t}_lineage ON {t}" for t in LINEAGE]
        drops += [f"DROP FUNCTION IF EXISTS orch_{t}_lineage_guard()" for t in LINEAGE]
        _run(drops)

    with op.batch_alter_table("events") as batch:
        batch.alter_column(
            "entity_id", existing_type=sa.String(length=128), type_=sa.String(length=36)
        )
    with op.batch_alter_table("evaluation_passes") as batch:
        batch.drop_constraint("uq_evaluation_passes_packet_id", type_="unique")
        batch.alter_column("eval_cycle_id", existing_type=sa.String(length=36), nullable=True)
        batch.create_unique_constraint(
            "uq_evaluation_passes_eval_cycle_id",
            ["eval_cycle_id", "field_name", "pass_no", "attempt"],
        )
    if _is_sqlite():  # the rebuilds dropped 0002's append-only triggers; restore them
        _run([s for t in ("evaluation_passes", "events") for s in _sqlite_append_only(t)])

    op.drop_table("field_registry_revisions")
    op.drop_table("ref_counters")
