def _backfill_legacy_cycles() -> None:
    """D4 risk 1: give every pre-existing ``eval_cycle_id`` a cycle row before the FK exists."""
    bind = op.get_bind()
    rows = bind.execute(
        sa.text(
            "SELECT ep.eval_cycle_id, MIN(ep.packet_id) AS packet_id FROM evaluation_passes ep "
            "GROUP BY ep.eval_cycle_id"
        )
    ).all()
    now = datetime.now(UTC)
    for cycle_id, packet_id in rows:
        version = bind.execute(
            sa.text("SELECT version FROM packets WHERE id = :id"), {"id": packet_id}
        ).scalar_one()
        bind.execute(
            sa.text(
                "INSERT INTO evaluation_cycles (id, packet_id, packet_version, phase, target_hash,"
                " pass_plan, models, state, created_at, updated_at) VALUES (:id, :pid, :v, 'pre',"
                " 'legacy', 'legacy', '{}', 'legacy', :now, :now)"
            ),
            {"id": cycle_id, "pid": packet_id, "v": version, "now": now},
        )


