def _sqlite_edit_schema(table: str, transform: Callable[[str], str]) -> None:
    """Change a SQLite table's stored definition without moving any row (D4 risk 2).

    SQLite's documented procedure for changes that do not alter the on-disk format: rewrite
    ``sqlite_master.sql`` under ``writable_schema`` and bump ``schema_version``. It is used only
    for (a) widening the status CHECK — every existing row stays valid — (b) adding nullable or
    defaulted columns at the *end* of the column list (exactly what ``ADD COLUMN`` does) and (c)
    adding FOREIGN KEY clauses, which are verified with ``foreign_key_check`` straight after.
    Indexes and triggers are never touched, so 0002/0004 guards survive unchanged.
    """
    bind = op.get_bind()
    old = bind.exec_driver_sql(
        "SELECT sql FROM sqlite_master WHERE type = 'table' AND name = ?", (table,)
    ).scalar_one()
    new = transform(old)
    if new == old:
        raise RuntimeError(f"{table}: schema edit matched nothing")
    version = bind.exec_driver_sql("PRAGMA schema_version").scalar_one()
    bind.exec_driver_sql("PRAGMA writable_schema = ON")
    bind.exec_driver_sql(
        "UPDATE sqlite_master SET sql = ? WHERE type = 'table' AND name = ?", (new, table)
    )
    bind.exec_driver_sql(f"PRAGMA schema_version = {int(version) + 1}")
    bind.exec_driver_sql("PRAGMA writable_schema = OFF")
    problems = bind.exec_driver_sql(f"PRAGMA foreign_key_check({table})").all()
    if problems:
        raise RuntimeError(f"foreign key violations in {table}: {problems[:5]}")


